export function getModules(locale: Locale): ModulePage[] {
  return modulePages.map((module) => {
    if (locale !== 'hi') return module
    const hi = hiBySlug[module.slug]
    return hi ? { ...module, ...hi, slug: module.slug, image: module.image } : module
  })
}

export function moduleBySlug(slug: string | undefined, locale: Locale = 'en') {
  return getModules(locale).find((module) => module.slug === slug)
}

